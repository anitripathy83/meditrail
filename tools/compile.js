// Compiles contracts/MediTrail.sol with the same settings to use in Remix:
// compiler 0.8.24, optimizer ON, 200 runs.
const solc = require('solc'); const fs = require('fs');
const src = fs.readFileSync(process.argv[2] || 'contracts/MediTrail.sol', 'utf8');
const input = { language: 'Solidity', sources: { 'MediTrail.sol': { content: src } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } } } };
const out = JSON.parse(solc.compile(JSON.stringify(input)));
(out.errors || []).forEach(e => console.error(e.severity, e.formattedMessage));
if ((out.errors || []).some(e => e.severity === 'error')) process.exit(1);
const c = out.contracts['MediTrail.sol'].MediTrail;
fs.writeFileSync(process.argv[3] || 'build.json', JSON.stringify({ compiler: solc.version(), abi: c.abi, bytecode: '0x' + c.evm.bytecode.object }, null, 1));
console.log('ok', solc.version(), '| bytecode bytes:', c.evm.bytecode.object.length / 2, '| abi entries:', c.abi.length);
// The website imports the ABI from web/abi.js.
fs.writeFileSync(require('path').join(__dirname, '../web/abi.js'),
  '// Generated by `npm run compile` from contracts/MediTrail.sol. Do not edit by hand.\nexport const ABI = ' + JSON.stringify(c.abi) + ';\n');
